import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const context = vm.createContext({ TextEncoder, TextDecoder, btoa, atob, console });
vm.runInContext(await readFile(new URL('../sync.js', import.meta.url), 'utf8'), context);
const core = context.ZhixingGitHubSyncCore;
const json = value => JSON.parse(JSON.stringify(value));
const state = (extra = {}) => ({ subject: '全部科目', chapter: '全部章节', questionType: 'all', mode: 'all', size: '20', records: {}, wrong: [], saved: [], session: { ids: ['q1', 'q2', 'q3'], order: 'sequential', index: 0, answers: {}, drafts: {} }, ...extra });
const initial = state({ records: { q1: { attempts: 4, correct: 2 } }, saved: ['q1'], wrong: ['q1'], session: { ...state().session, answers: { q1: 'A' } } });
const base = core.migrate(initial);
assert.deepEqual(json(core.materialize(base)), initial);
const oldState = state({ records: { q1: { attempts: 2, correct: 1 } }, saved: ['q1'], wrong: ['q1'] });
const aState = json(initial); aState.records.q1 = { attempts: 5, correct: 3 }; aState.saved = []; aState.wrong = []; aState.session.answers.q2 = 'BC';
const bState = json(initial); bState.records.q1 = { attempts: 5, correct: 2 }; bState.session.answers.q3 = { revealed: true, correct: false };
const a = core.capture(base, initial, aState, 'device-a', 100);
const b = core.capture(base, initial, bState, 'device-b', 100);
const combined = core.merge(a, b), merged = core.materialize(combined);
assert.deepEqual(json(merged.records.q1), { attempts: 6, correct: 3 }, 'independent device attempts add exactly once');
assert.deepEqual(json(merged.saved), [], 'saved deletion survives stale device');
assert.deepEqual(json(merged.wrong), [], 'wrong deletion survives stale device');
assert.deepEqual(json(merged.session.answers), { q1: 'A', q2: 'BC', q3: { revealed: true, correct: false } }, 'same round merges answers per question');
assert.deepEqual(json(core.merge(combined, combined)), json(combined), 'merge is idempotent');
assert.deepEqual(json(core.materialize(core.merge(a, b))), json(core.materialize(core.merge(b, a))), 'merge is commutative');
assert.equal(JSON.stringify(core.stable(core.merge(a,b))), JSON.stringify(core.stable(core.merge(b,a))), 'canonical storage prevents cross-tab event ping-pong');
assert.deepEqual(json(core.materialize(core.merge(combined, core.migrate(oldState))).records.q1), { attempts: 6, correct: 3 }, 'old aggregate never overwrites new counts');
assert.deepEqual(json(core.materialize(core.merge(combined, core.migrate(oldState))).saved), [], 'legacy import cannot resurrect deleted saved item');
const restored = json(merged); restored.saved = ['q1'];
const restoredDoc = core.capture(combined, merged, restored, 'device-b', 50);
assert.deepEqual(json(core.materialize(core.merge(a, restoredDoc)).saved), ['q1'], 'observed clock beats skewed wall clock');
const newerRound = json(merged); newerRound.session = { ...state().session, answers: {} };
const nextRound = core.capture(combined, merged, newerRound, 'device-a', 300);
assert.deepEqual(json(core.materialize(core.merge(nextRound, b)).session.answers), {}, 'new round does not restore old answers');
assert.deepEqual(json(core.decode(core.encode(combined))), json(combined), 'Unicode base64');
assert.throws(() => core.normalize({ format: 'zhixing-progress', version: 99 }), /版本/);
assert.throws(() => core.normalize({ arbitrary: 'data' }), /格式/);
assert.equal(JSON.stringify(combined).includes('github_pat_'), false);
const response = (status, body) => ({ ok: status >= 200 && status < 300, status, json: async () => json(body) });
let cloud = core.migrate(initial), sha = 'first', conflicts = 0, reads = 0, writes = 0;
const requests = [];
const fetcher = async (url, options) => {
  requests.push({ url, options });
  if (!url.includes('/contents/')) return response(200, { private: false });
  if (!options.method) { assert.equal(new URL(url).searchParams.get('ref'), 'progress'); reads++; return response(200, { sha, encoding: 'base64', content: core.encode(cloud) }); }
  writes++;
  const body = JSON.parse(options.body); assert.equal(body.branch, 'progress'); assert.equal(body.sha, sha);
  if (conflicts++ === 0) { cloud = core.merge(cloud, b); sha = 'second'; return response(409, {}); }
  cloud = core.decode(body.content); sha = 'third'; return response(200, { content: { sha } });
};
let local = a;
await core.synchronize(new core.GitHubClient({ owner: '211820252', repo: 'zhixing-question-bank', path: 'progress/personal.json', branch: 'progress' }, 'test-secret', fetcher), () => local, doc => { local = doc; });
assert.equal(reads, 2); assert.equal(writes, 2);
assert.deepEqual(json(core.materialize(cloud).records.q1), { attempts: 6, correct: 3 }, '409 retry pulls concurrent progress');
assert.equal(requests.filter(x => x.url.includes('test-secret')).length, 0);
assert.equal(requests.every(x => x.options.headers.Authorization === 'Bearer test-secret'), true);
assert.equal(requests.filter(x => x.options.method === 'PUT').every(x => !x.options.body.includes('test-secret')), true);
let accepted = false;
await assert.rejects(core.synchronize(new core.GitHubClient({ owner: 'x', repo: 'y', path: 'p.json' }, 'secret', async () => { throw new TypeError('offline'); }), () => local, () => { accepted = true; }), /offline/);
assert.equal(accepted, false, 'offline preserves local doc');
assert.deepEqual(json(core.materialize(local).records.q1), { attempts: 6, correct: 3 });
let putBody;
const newFileClient = new core.GitHubClient({ owner: 'x', repo: 'y', path: 'p.json' }, 'secret', async (url, options) => {
  if (!url.includes('/contents/')) return response(200, { private: false });
  if (!options.method) return response(404, {});
  putBody = JSON.parse(options.body); return response(201, {});
});
await core.synchronize(newFileClient, () => base, () => {});
assert.equal(Object.hasOwn(putBody, 'sha'), false, 'first file creation omits sha');
let deniedWrites = 0;
const denied = new core.GitHubClient({ owner: 'x', repo: 'y', path: 'p.json' }, 'secret', async (url, options) => { if (options.method) deniedWrites++; return response(404, {}); });
await assert.rejects(core.synchronize(denied, () => base, () => {}), /仓库不可访问/);
assert.equal(deniedWrites, 0, 'repository 404 is not treated as empty file');
console.log('Sync tests passed: legacy migration, concurrent attempts, deletions, logical clocks, per-question answers, Unicode, SHA conflict retry, offline preservation, initial upload and token boundaries.');
